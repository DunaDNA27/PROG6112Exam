public class SalesProcessor {

    private static final double VAT_RATE = 0.15;        // 15% VAT
    private static final double COMMISSION_RATE = 0.15; // 15% Commission

    public static double calculateVAT(double amount) {
        return amount * VAT_RATE;
    }

    public static double calculateCommission(double amount) {
        return amount * COMMISSION_RATE;
    }

    public static double calculateTotalSales(double amount) {
        double vat = calculateVAT(amount);
        double commission = calculateCommission(amount);
        return amount + vat + commission;
    }
}



private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {
    try {
        double amount = Double.parseDouble(txtAmount.getText());

        if (amount < 0) {
            JOptionPane.showMessageDialog(this, "Amount cannot be negative.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double vat = SalesProcessor.calculateVAT(amount);
        double commission = SalesProcessor.calculateCommission(amount);
        double total = SalesProcessor.calculateTotalSales(amount);

        lblVAT.setText(String.format("VAT: %.2f", vat));
        lblCommission.setText(String.format("Commission: %.2f", commission));
        lblTotal.setText(String.format("Total Sales: %.2f", total));

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter a valid numeric amount.", "Invalid Input", JOptionPane.ERROR_MESSAGE);
    }
}


